import { useEffect, useRef, useState } from "react";
import { activityDate } from "../../../shared/lib/date-utils.js";

export function usePlannerDrag({ day, changes }) {
  const cleanup = useRef(() => {});
  const suppressClick = useRef(false);
  const [preview, setPreview] = useState("");
  const [ghost, setGhost] = useState(null);
  useEffect(() => () => cleanup.current(), []);
  const beginDrag = (event, item, edge = "move") => {
    if (event.button !== 0 || item.isLocked || item.source.isOnboardingSample || changes.isSavingTimeChanges) return;
    event.stopPropagation();
    const handle = event.currentTarget;
    const origin = handle.closest(".daily-planner-lanes").getBoundingClientRect();
    const x = event.clientX, y = event.clientY;
    const start = activityDate(item.source.start), end = activityDate(item.source.end);
    let moved = false, next = null;
    const move = e => {
      if (Math.hypot(e.clientX - x, e.clientY - y) < 5 && !moved) return;
      moved = true;
      suppressClick.current = true;
      setGhost({ title: item.title, color: item.color.border, x: e.clientX, y: e.clientY });
      // Choose the nearest open day even over its heading/footer or outside the axis.
      // This keeps the snapped layout visible continuously, before pointerup.
      const targets = [...document.querySelectorAll(".daily-planner-lanes[data-day]")];
      const distance = el => {
        const r = el.closest(".daily-planner").getBoundingClientRect();
        return Math.max(r.top - e.clientY, e.clientY - r.bottom, 0);
      };
      const target = edge === "move" ? targets.sort((a, b) => distance(a) - distance(b))[0] : handle;
      if (!target) return;
      const targetDay = edge === "move" ? new Date(target.dataset.day) : day;
      const rect = edge === "move" ? target.getBoundingClientRect() : origin;
      const rawDelta = ((e.clientX - rect.left) / rect.width - (x - origin.left) / origin.width) * 1440;
      const dayShift = targetDay.getTime() - day.getTime();
      const snapTime = date => {
        const snapped = new Date(date);
        const minutes = snapped.getHours() * 60 + snapped.getMinutes() + snapped.getSeconds() / 60 + snapped.getMilliseconds() / 60000;
        snapped.setHours(0, Math.round(minutes / 15) * 15, 0, 0);
        return snapped;
      };
      let newStart = new Date(start), newEnd = new Date(end);
      if (item.isAllDay) {
        newStart = new Date(+start + dayShift);
        newEnd = new Date(+end + dayShift);
      } else if (edge === "move") {
        const proposed = snapTime(new Date(+start + dayShift + rawDelta * 60000));
        // Keep the grabbed segment within the destination day's clock.
        const segmentOffset = +item.start - +start;
        const first = +targetDay - segmentOffset;
        const last = +targetDay + 1425 * 60000 - segmentOffset;
        newStart = new Date(Math.max(first, Math.min(last, +proposed)));
        newEnd = new Date(+newStart + (+end - +start));
      } else if (edge === "start") {
        newStart = snapTime(new Date(+start + rawDelta * 60000));
        if (+newStart > +end - 15 * 60000) {
          newStart = new Date(end);
          newStart.setSeconds(0, 0);
          newStart.setMinutes(Math.floor((newStart.getMinutes() - 15) / 15) * 15);
        }
      } else {
        newEnd = snapTime(new Date(+end + rawDelta * 60000));
        if (+newEnd < +start + 15 * 60000) {
          newEnd = new Date(start);
          const minute = newEnd.getMinutes() + (newEnd.getSeconds() || newEnd.getMilliseconds() ? 1 : 0);
          newEnd.setSeconds(0, 0);
          newEnd.setMinutes(Math.ceil((minute + 15) / 15) * 15);
        }
      }
      next = { id: item.calendarId, start: newStart, end: newEnd };
      changes.setDragPreview(next);
      const format = date => date.toLocaleString("th-TH", { day: "numeric", month: "short", ...(item.isAllDay ? {} : { hour: "2-digit", minute: "2-digit", hour12: false }) });
      const changeMinutes = Math.round(((edge === "end" ? +newEnd - +end : +newStart - +start) / 60000));
      const deltaLabel = `${changeMinutes > 0 ? "+" : ""}${changeMinutes} นาที`;
      setPreview(`${item.title}: ${format(newStart)} – ${format(newEnd)} (${deltaLabel}) · ปล่อยเพื่อใช้ฉบับร่าง · Esc ยกเลิก`);
    };
    const finish = e => {
      if (e.type === "pointerup" && moved && next && (+next.start !== +start || +next.end !== +end)) changes.queueTimeChanges([next]);
      cleanup.current();
      // The click generated by pointerup must not open the edit dialog.
      setTimeout(() => { suppressClick.current = false; }, 0);
    };
    const key = e => { if (e.key === "Escape") { next = null; finish(e); } };
    cleanup.current = () => {
      window.removeEventListener("pointermove", move);
      window.removeEventListener("pointerup", finish);
      window.removeEventListener("pointercancel", finish);
      window.removeEventListener("keydown", key);
      changes.setDragPreview(null);
      setGhost(null);
      setPreview("");
    };
    window.addEventListener("pointermove", move);
    window.addEventListener("pointerup", finish);
    window.addEventListener("pointercancel", finish);
    window.addEventListener("keydown", key);
  };
  return { beginDrag, suppressClick, preview, ghost };
}
