import { createServer } from '../node_modules/vite/dist/node/index.js';
import react from '../node_modules/@vitejs/plugin-react/dist/index.js';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const root = fileURLToPath(new URL('../', import.meta.url));
const devMockupsAlias = fileURLToPath(new URL('../src/app/dev-mockups.production.jsx', import.meta.url));
const server = await createServer({ root, configFile: false, resolve: { alias: { '@dev-mockups': devMockupsAlias } }, plugins: [{ name: 'isolated-phase1-apis', enforce: 'pre', load(id) {
  if (id.replaceAll('\\', '/').endsWith('/features/activity/api/archive.js')) return `export const fetchActivityArchive = async () => window.phase1.archive; export const saveActivityArchiveItem = async item => { window.phase1.archive = [...window.phase1.archive.filter(i => i.archiveId !== item.archiveId), item]; }; export const deleteActivityArchiveItem = async id => { window.phase1.archive = window.phase1.archive.filter(i => i.archiveId !== id); };`;
  if (id.replaceAll('\\', '/').endsWith('/features/calendar-connection/api/google-calendar.js')) return `export const fetchActivities = async () => window.phase1.cycleActivities;`;
} }, react()], server: { host: '127.0.0.1', port: 0 }, logLevel: 'error' });
await server.listen();
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, timezoneId: 'Asia/Bangkok' });
const errors = [];
page.setDefaultTimeout(10000);
page.on('pageerror', error => errors.push(error.message));
await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
const origin = server.resolvedUrls.local[0];
const block = title => page.locator(`.week-spine-block[title="${title}"]`);
try {
  await page.goto(origin + 'tests/fixtures/activity-phase1.html');
  await block('Activity A').waitFor();
  assert.equal(await page.locator('.week-spine-fullscreen-btn').count(), 0);
  assert.equal(await page.locator('.week-spine-hours').count(), 0);
  assert.equal(await page.locator('.week-spine-resize-handle').count(), 0);
  assert.ok((await page.locator('.week-spine-block').evaluateAll(items => items.map(item => item.getBoundingClientRect().height))).every(height => height === 60));
  await block('Activity A').click();
  assert.ok(await page.evaluate(() => window.phase1.calls.some(c => c.type === 'edit' && c.value === 'Activity A')));
  await page.locator('.week-spine-list-add').nth(1).click();
  assert.ok(await page.evaluate(() => window.phase1.calls.some(c => c.type === 'add')));
  await block('Activity A').click({ button: 'right' });
  await page.getByText('ทำสำเนา', { exact: true }).click();
  await page.waitForFunction(() => window.phase1.calls.filter(c => c.type === 'copy').length === 1);
  const copied = await page.evaluate(() => window.phase1.calls.find(c => c.type === 'copy').value);
  assert.equal(copied.id, 'Activity A');
  assert.ok(copied.start.dateTime && copied.end.dateTime, 'copy retains real start and end times');
  await block('Activity A').click({ button: 'right' });
  await page.getByText('เลือกรายการ', { exact: true }).click();
  await block('Activity B').click();
  assert.equal(await page.locator('.is-series-selected').count(), 2);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.is-series-selected').count(), 0);
  await block('Locked').click();
  assert.ok(!(await page.evaluate(() => window.phase1.calls.some(c => c.type === 'edit' && c.value === 'Locked'))));
  assert.match(await page.getByRole('alert').textContent(), /ล็อก/);
  await page.locator('.week-spine-all-day-track-block').first().click({ button: 'right' });
  await page.getByText("ย้ายวัน", { exact: true }).click();
  await page.locator('.activity-popup input[type="date"]').fill('2026-09-09');
  await page.locator('.activity-popup').getByRole('button', { name: 'ยืนยันย้ายวัน', exact: true }).click();
  await page.waitForFunction(() => window.phase1.calls.some(c => c.type === 'move-day'));
  await page.evaluate(() => window.phase1.set({ viewMode: 'four-weeks' }));
  await page.locator('.week-spine-overview-week').first().waitFor();
  await page.locator('.week-spine-overview-fullscreen-btn').first().click();
  await page.locator('.week-spine-track').first().waitFor();
  assert.equal(await page.locator('.is-fullscreen').count(), 0);
  await page.evaluate(() => window.phase1.set({ viewMode: 'four-weeks' }));
  await page.locator('.week-spine-overview-week').first().waitFor();
  await page.locator('.week-spine-overview-week').first().dblclick({ position: { x: 5, y: 5 } });
  await page.locator('.week-spine-track').first().waitFor();
  assert.equal(await page.locator('.is-fullscreen').count(), 0);
  await page.screenshot({ path: join(tmpdir(), 'times-activity-phase1.png'), fullPage: true });
  assert.deepEqual(errors, []);
  console.log('PASS browser: fixed-height lists, edit/add, locked activity, multi-selection, copy, move date and Cycle navigation; no uncaught errors');
} finally { await browser.close(); await server.close(); }
